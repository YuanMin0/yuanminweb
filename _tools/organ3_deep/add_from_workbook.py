def main():
    write = '--write' in sys.argv
    s = open(PATH, encoding='utf-8').read()
    total = 0
    for title, items in ADD.items():
        i = s.find('"title": %s' % json.dumps(title, ensure_ascii=False))
        assert i > 0, title
        j = s.find('"quiz": [', i)
        assert j > 0, title
        # 查重
        block_end = s.find('\n        }', j)
        seg = s[j:block_end if block_end > 0 else j + 20000]
        new_items = [it for it in items if json.dumps(it['stem'], ensure_ascii=False)[1:-1] not in seg]
        chunks = []
        for it in new_items:
            t = json.dumps(it, ensure_ascii=False, indent=2)
            chunks.append('\n'.join('            ' + ln for ln in t.split('\n')))
        if not chunks:
            print('  跳过（已存在）:', title)
            continue
        txt = ',\n'.join(chunks)
        pos = j + len('"quiz": [')
        s = s[:pos] + '\n' + txt + ',' + s[pos:]
        total += len(new_items)
        print('  %s +%d' % (title, len(new_items)))
    print('新增', total, '题')
    if write:
        open(PATH, 'w', encoding='utf-8', newline='').write(s)
        print('已写入')

if __name__ == '__main__':
    main()
