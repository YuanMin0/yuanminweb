def main():
    write = '--write' in sys.argv
    s = open(PATH, encoding='utf-8').read()
    ok = 0
    for title, head, html in ITEMS:
        ti = s.find('<h3>%s</h3>' % title)
        if ti < 0:
            print('未找到块:', title)
            continue
        # 块范围
        nxt = s.find('<article class="knowledge-block"', ti + 10)
        seg = s[ti: nxt if nxt > 0 else len(s)]
        hi = seg.find('<p>%s</p>' % head)
        if hi < 0:
            print('未找到标题:', title, '|', head)
            continue
        pos = ti + hi + len('<p>%s</p>' % head)
        s = s[:pos] + html + s[pos:]
        ok += 1
    print('匹配并插入', ok, '/', len(ITEMS))
    if write:
        open(PATH, 'w', encoding='utf-8', newline='').write(s)
        print('已写入')


if __name__ == '__main__':
    main()
